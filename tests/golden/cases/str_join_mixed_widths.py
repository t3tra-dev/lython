# 実行が必要な理由: join が要素を「幅が同じならバイト列として」運ぶようになった
# ので、区切りと要素の幅が食い違う組み合わせが値として正しいことは実行でしか
# 確かめられない。同幅ならバイト経路、違えば 1 文字ずつ広げる経路に落ちる。

# 狭い区切り × 広い要素。
print("-".join(["✓", "é", "a"]))
# 広い区切り × 狭い要素。
print("✓".join(["a", "b", "c"]))
# 幅が全部そろっている (バイト経路)。
print("-".join(["ab", "cd"]))
print("✓".join(["é", "é"]))
# 空の区切り・空の要素・要素 1 個・要素 0 個。
print("".join(["✓", "a"]))
print("-".join([""]))
print("-".join(["✓"]))
print("-".join([]))
# 出力の幅は入るうち最小でなければならない: 全部 ASCII なら latin-1。
print("-".join(["a", "b"]) == "a-b")
print(len("✓".join(["a", "b"])))
